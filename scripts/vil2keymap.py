#!/usr/bin/env python3
"""Generate the QMK keymap sources from the Vial layout file.

    layout/cornelious.vil  ->  qmk/keyboards/cornelious/keymaps/vial/keymap.c
                           ->  qmk/keyboards/cornelious/keymaps/vial/layout_settings.h

The .vil file (Vial: File > Save current layout) is the single source of truth.
Everything in it is baked into the firmware as the factory defaults:
  - every layer of the keymap
  - tap dances, combos, key overrides, alt-repeat keys and macros
  - QMK Settings (tapping term etc.)
so a freshly flashed board comes up with the full layout and needs no extra steps.

Keycode names are decoded with vial-gui's own tables (the same code the Vial app
uses) and printed with the names from vial-qmk's quantum/keycodes.h.

Usage:
    python3 scripts/vil2keymap.py --qmk /path/to/vial-qmk [--vial-gui /path/to/vial-gui]
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VIAL_GUI_REPO = "https://github.com/vial-kb/vial-gui.git"
VIAL_GUI_TAG = "v0.7.5"

KB_DIR = os.path.join(ROOT, "qmk", "keyboards", "cornelious")
OUT_DIR = os.path.join(KB_DIR, "keymaps", "vial")

# QMK Settings id -> config.h macro, for settings that have one. Settings without a
# macro (bit flags) are only applied at runtime by the generated keymap.c.
QSID_MACROS = {
    2: "COMBO_TERM",
    4: "AUTO_SHIFT_TIMEOUT",
    5: "ONESHOT_TAP_TOGGLE",
    6: "ONESHOT_TIMEOUT",
    7: "TAPPING_TERM",
    9: "MOUSEKEY_DELAY",
    10: "MOUSEKEY_INTERVAL",
    11: "MOUSEKEY_MOVE_DELTA",
    12: "MOUSEKEY_MAX_SPEED",
    13: "MOUSEKEY_TIME_TO_MAX",
    14: "MOUSEKEY_WHEEL_DELAY",
    15: "MOUSEKEY_WHEEL_INTERVAL",
    16: "MOUSEKEY_WHEEL_MAX_SPEED",
    17: "MOUSEKEY_WHEEL_TIME_TO_MAX",
    18: "TAP_CODE_DELAY",
    19: "TAP_HOLD_CAPS_DELAY",
    20: "TAPPING_TOGGLE",
}

HEADER = (
    "// GENERATED by scripts/vil2keymap.py from layout/cornelious.vil. Do not edit by hand.\n"
    "// To change the layout: edit it in Vial, save it over layout/cornelious.vil\n"
    "// (File > Save current layout), then rebuild (scripts/build.sh).\n"
)


# --------------------------------------------------------------------------- vial-gui


def ensure_vial_gui(path):
    if path is None:
        path = os.path.join(ROOT, ".cache", "vial-gui")
    if not os.path.isdir(os.path.join(path, "src", "main", "python")):
        print("cloning vial-gui {} into {}".format(VIAL_GUI_TAG, path), file=sys.stderr)
        subprocess.check_call(["git", "clone", "-q", "--depth", "1", "--branch", VIAL_GUI_TAG, VIAL_GUI_REPO, path])
    return os.path.join(path, "src", "main", "python")


class FakeKeyboard:
    """The few attributes vial-gui's keycode tables need from a connected keyboard."""

    def __init__(self, vil):
        self.vial_protocol = vil.get("vial_protocol", 6)
        self.layers = len(vil["layout"])
        self.macro_count = len(vil.get("macro", []))
        self.tap_dance_count = len(vil.get("tap_dance", []))
        self.custom_keycodes = None
        self.midi = None
        self.supported_features = set()


def load_vial_gui(src, vil):
    sys.path.insert(0, src)
    from keycodes import keycodes as kcmod  # noqa: E402
    from macro import macro_action  # noqa: E402

    kcmod.recreate_keyboard_keycodes(FakeKeyboard(vil))
    return kcmod.Keycode, macro_action


# --------------------------------------------------------------------------- QMK names


def qmk_names(qmk_root):
    """value -> preferred QMK name, parsed from vial-qmk's quantum/keycodes.h."""
    path = os.path.join(qmk_root, "quantum", "keycodes.h")
    text = open(path, encoding="utf-8").read()
    values = {}
    order = []
    for m in re.finditer(r"^\s+((?:KC|QK)_\w+)\s*=\s*(0x[0-9A-Fa-f]+)\s*,", text, re.M):
        values[m.group(1)] = int(m.group(2), 16)
        order.append(m.group(1))
    # aliases: enum entries `KC_TRNS = KC_TRANSPARENT,` and `#define KC_X KC_Y`
    alias_re = r"^(?:\s+((?:KC|QK)_\w+)\s*=\s*((?:KC|QK)_\w+)\s*,|#define\s+((?:KC|QK)_\w+)\s+((?:KC|QK)_\w+)\s*$)"
    for m in re.finditer(alias_re, text, re.M):
        name, target = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), m.group(4))
        if target in values and name not in values:
            values[name] = values[target]
            order.append(name)
    best = {}
    for name in order:  # shortest name wins, ties go to the first defined
        v = values[name]
        if v not in best or len(name) < len(best[v]):
            best[v] = name
    for must in ("KC_NO", "KC_TRNS", "KC_A", "QK_MACRO_0"):
        if must not in values:
            sys.exit("could not parse {} from {}".format(must, path))
    return best


MODS_L = [(0x01, "LCTL"), (0x02, "LSFT"), (0x04, "LALT"), (0x08, "LGUI")]
MODS_R = [(0x01, "RCTL"), (0x02, "RSFT"), (0x04, "RALT"), (0x08, "RGUI")]


def mod_bits(mods5):
    """5-bit QMK mod mask -> 'MOD_LCTL | MOD_LSFT'."""
    table = MODS_R if mods5 & 0x10 else MODS_L
    names = ["MOD_" + n for bit, n in table if mods5 & bit]
    return " | ".join(names) if names else "0"


class Formatter:
    def __init__(self, names):
        self.names = names

    def basic(self, code):
        return self.names.get(code, "0x{:02X}".format(code))

    def __call__(self, code):
        if code <= 0x00FF:
            return self.basic(code)
        if 0x7700 <= code <= 0x777F:  # QK_MACRO
            return "QK_MACRO_{}".format(code - 0x7700)
        if code > 0x57FF and code in self.names:  # quantum keycodes (QK_GESC, ...)
            return self.names[code]
        if 0x0100 <= code <= 0x1FFF:  # QK_MODS: modifier(s) + key
            mods5, kc = (code >> 8) & 0x1F, code & 0xFF
            table = MODS_R if mods5 & 0x10 else MODS_L
            out = self.basic(kc)
            for bit, name in reversed(table):
                if mods5 & bit:
                    out = "{}({})".format(name, out)
            return out
        if 0x2000 <= code <= 0x3FFF:  # QK_MOD_TAP
            return "MT({}, {})".format(mod_bits((code >> 8) & 0x1F), self.basic(code & 0xFF))
        if 0x4000 <= code <= 0x4FFF:  # QK_LAYER_TAP
            return "LT({}, {})".format((code >> 8) & 0x0F, self.basic(code & 0xFF))
        if 0x5000 <= code <= 0x51FF:  # QK_LAYER_MOD
            return "LM({}, {})".format((code >> 5) & 0x0F, mod_bits(code & 0x1F))
        for base, fn in ((0x5200, "TO"), (0x5220, "MO"), (0x5240, "DF"), (0x5260, "TG"),
                         (0x5280, "OSL"), (0x52C0, "TT"), (0x52E0, "PDF")):
            if base <= code < base + 0x20:
                return "{}({})".format(fn, code - base)
        if 0x52A0 <= code <= 0x52BF:
            return "OSM({})".format(mod_bits(code & 0x1F))
        if 0x5700 <= code <= 0x57FF:
            return "TD({})".format(code & 0xFF)
        return self.names.get(code, "0x{:04X}".format(code))


# --------------------------------------------------------------------------- layout


def layout_rows(info_path):
    """LAYOUT key order from info.json, grouped into printed rows with column slots."""
    info = json.load(open(info_path, encoding="utf-8"))
    keys = info["layouts"]["LAYOUT"]["layout"]
    rows, cur = [], []
    for k in keys:
        if cur and k["x"] < cur[-1]["x"]:
            rows.append(cur)
            cur = []
        cur.append(k)
    rows.append(cur)
    # column slots from the x positions of the main rows (rows without rotated keys)
    xs = sorted({k["x"] for row in rows if all("r" not in k for k in row) for k in row})
    centre = (xs[0] + xs[-1]) / 2
    left_cols = [x for x in xs if x < centre]
    out = []
    for row in rows:
        if all("r" not in k for k in row):
            out.append([(xs.index(k["x"]), tuple(k["matrix"])) for k in row])
        else:  # thumb row: hug the centre
            left = [k for k in row if k["x"] < centre]
            right = [k for k in row if k["x"] >= centre]
            start = len(left_cols) - len(left)
            out.append([(start + i, tuple(k["matrix"])) for i, k in enumerate(left)] +
                       [(len(left_cols) + i, tuple(k["matrix"])) for i, k in enumerate(right)])
    return out, len(left_cols), len(xs)


def render_layer(rows, split_at, ncols, cells):
    width = max(len(c) for c in cells.values()) + 1
    lines = []
    for row in rows:
        slots = [""] * ncols
        for slot, rc in row:
            slots[slot] = cells[rc] + ","
        parts = [s.ljust(width + 1) for s in slots]
        line = "".join(parts[:split_at]) + "    " + "".join(parts[split_at:])
        lines.append("        " + line.rstrip())
    text = "\n".join(lines)
    return text[: text.rfind(",")] + text[text.rfind(",") + 1:]  # drop trailing comma


# --------------------------------------------------------------------------- main


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--vil", default=os.path.join(ROOT, "layout", "cornelious.vil"))
    ap.add_argument("--qmk", default=os.environ.get("VIAL_QMK"), help="vial-qmk checkout (for keycode names)")
    ap.add_argument("--vial-gui", default=os.environ.get("VIAL_GUI"), help="vial-gui checkout (auto-cloned if absent)")
    ap.add_argument("--out", default=OUT_DIR)
    args = ap.parse_args()
    if not args.qmk:
        ap.error("--qmk (or $VIAL_QMK) is required")

    vil = json.load(open(args.vil, encoding="utf-8"))
    if vil.get("vial_protocol", 6) < 6:
        sys.exit("this generator expects a .vil saved from Vial protocol 6 or newer")

    Keycode, macro_action = load_vial_gui(ensure_vial_gui(args.vial_gui), vil)
    fmt = Formatter(qmk_names(args.qmk))

    def code(v):
        return Keycode.deserialize(v)

    rows, split_at, ncols = layout_rows(os.path.join(KB_DIR, "info.json"))
    layout_rc = [rc for row in rows for _, rc in row]

    # ---- layers
    layers = vil["layout"]
    used = len(layers)
    while used > 1 and all(code(layers[used - 1][r][c]) == 1 for r, c in layout_rc):
        used -= 1  # trailing all-transparent layers need not be spelled out
    out = [HEADER, "#include QMK_KEYBOARD_H", "#include \"dynamic_keymap.h\"", "#include \"via.h\"",
           "#include \"qmk_settings.h\"", "", "// clang-format off",
           "const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {"]
    for li in range(used):
        cells = {(r, c): fmt(code(layers[li][r][c])) for r, c in layout_rc}
        out.append("    [{}] = LAYOUT(".format(li))
        out.append(render_layer(rows, split_at, ncols, cells))
        out.append("    ),")
    out.append("};")
    out.append("// clang-format on")
    if used < len(layers):
        out.append("// Layers {}-{} are all KC_TRNS.".format(used, len(layers) - 1))
    out.append("")

    # ---- dynamic entries
    # The firmware resets every tap dance to {KC_NO x4, TAPPING_TERM}; write the ones that differ.
    tapping_term = int(vil.get("settings", {}).get("7", 200))
    td = [(i, [code(x) for x in e[:4]] + [e[4]]) for i, e in enumerate(vil.get("tap_dance", []))]
    td = [(i, e) for i, e in td if any(e[:4]) or e[4] != tapping_term]
    combos = [(i, [code(x) for x in e]) for i, e in enumerate(vil.get("combo", []))]
    combos = [(i, e) for i, e in combos if e[4] and any(e[:4])]
    kos = [(i, e) for i, e in enumerate(vil.get("key_override", [])) if code(e["trigger"]) or code(e["replacement"])]
    arks = [(i, e) for i, e in enumerate(vil.get("alt_repeat_key", [])) if code(e["keycode"]) or code(e["alt_keycode"])]

    tags = {"text": macro_action.ActionText, "tap": macro_action.ActionTap, "down": macro_action.ActionDown,
            "up": macro_action.ActionUp, "delay": macro_action.ActionDelay}
    macros = []
    for m in vil.get("macro", []):
        acts = []
        for a in m:
            obj = tags[a[0]]()
            obj.restore(a)
            acts.append(obj)
        macros.append(b"".join(a.serialize(vil["vial_protocol"]) for a in acts))
    macro_blob = b"\x00".join(macros) + b"\x00" if any(macros) else b""

    settings = sorted((int(k), int(v)) for k, v in vil.get("settings", {}).items())

    out.append("// Vial dynamic features from the .vil, written to EEPROM whenever it is reset")
    out.append("// (first boot, or first boot after flashing a new build).")
    out.append("typedef struct { uint8_t i; vial_tap_dance_entry_t e; } td_default_t;")
    out.append("static const td_default_t td_defaults[] = {")
    for i, e in td:
        out.append("    {{ {:2d}, {{ {}, {}, {}, {}, {} }} }},".format(i, *[fmt(x) for x in e[:4]], e[4]))
    out.append("};")
    if combos:
        out.append("typedef struct { uint8_t i; vial_combo_entry_t e; } combo_default_t;")
        out.append("static const combo_default_t combo_defaults[] = {")
        for i, e in combos:
            out.append("    {{ {:2d}, {{ {{ {}, {}, {}, {} }}, {} }} }},".format(i, *[fmt(x) for x in e]))
        out.append("};")
    if kos:
        out.append("typedef struct { uint8_t i; vial_key_override_entry_t e; } ko_default_t;")
        out.append("static const ko_default_t ko_defaults[] = {")
        for i, e in kos:
            out.append("    {{ {:2d}, {{ {}, {}, 0x{:04X}, 0x{:02X}, 0x{:02X}, 0x{:02X}, 0x{:02X} }} }},".format(
                i, fmt(code(e["trigger"])), fmt(code(e["replacement"])), e["layers"], e["trigger_mods"],
                e["negative_mod_mask"], e["suppressed_mods"], e["options"]))
        out.append("};")
    if arks:
        out.append("typedef struct { uint8_t i; vial_alt_repeat_key_entry_t e; } ark_default_t;")
        out.append("static const ark_default_t ark_defaults[] = {")
        for i, e in arks:
            out.append("    {{ {:2d}, {{ {}, {}, 0x{:02X}, 0x{:02X} }} }},".format(
                i, fmt(code(e["keycode"])), fmt(code(e["alt_keycode"])), e["allowed_mods"], e["options"]))
        out.append("};")
    if macro_blob:
        out.append("static const uint8_t macro_defaults[] = {")
        for k in range(0, len(macro_blob), 16):
            out.append("    " + ", ".join("0x{:02X}".format(b) for b in macro_blob[k:k + 16]) + ",")
        out.append("};")
    out.append("typedef struct { uint16_t qsid; uint32_t value; } qs_default_t;")
    out.append("static const qs_default_t qs_defaults[] = {")
    for q, v in settings:
        out.append("    {{ {:2d}, {} }},{}".format(q, v, "  // " + QSID_MACROS[q] if q in QSID_MACROS else ""))
    out.append("};")
    out.append("")
    out.append("static void cornelious_apply_layout_defaults(void) {")
    out.append("    for (uint8_t k = 0; k < ARRAY_SIZE(td_defaults); k++) dynamic_keymap_set_tap_dance(td_defaults[k].i, &td_defaults[k].e);")
    if combos:
        out.append("    for (uint8_t k = 0; k < ARRAY_SIZE(combo_defaults); k++) dynamic_keymap_set_combo(combo_defaults[k].i, &combo_defaults[k].e);")
    if kos:
        out.append("    for (uint8_t k = 0; k < ARRAY_SIZE(ko_defaults); k++) dynamic_keymap_set_key_override(ko_defaults[k].i, &ko_defaults[k].e);")
    if arks:
        out.append("    for (uint8_t k = 0; k < ARRAY_SIZE(ark_defaults); k++) dynamic_keymap_set_alt_repeat_key(ark_defaults[k].i, &ark_defaults[k].e);")
    if macro_blob:
        out.append("    dynamic_keymap_macro_set_buffer(0, sizeof(macro_defaults), (uint8_t *)macro_defaults);")
    out.append("    for (uint8_t k = 0; k < ARRAY_SIZE(qs_defaults); k++) {")
    out.append("        uint32_t v = qs_defaults[k].value;")
    out.append("        qmk_settings_set(qs_defaults[k].qsid, &v, sizeof(v)); // ids this firmware lacks are ignored")
    out.append("    }")
    if combos or kos or arks:
        out.append("    // combos, key overrides and alt-repeat keys are cached at boot: restart to load them")
        out.append("    soft_reset_keyboard();")
    out.append("}")
    out.append("")
    out.append("// Full EEPROM reset (brand-new board, or eeconfig wiped).")
    out.append("void eeconfig_init_user(void) {")
    out.append("    cornelious_apply_layout_defaults();")
    out.append("}")
    out.append("")
    out.append("// Vial resets its EEPROM data on the first boot of every new build.")
    out.append("void via_init_kb(void) {")
    out.append("    if (!via_eeprom_is_valid()) {")
    out.append("        eeconfig_init_via();")
    out.append("        cornelious_apply_layout_defaults();")
    out.append("    }")
    out.append("}")
    open(os.path.join(args.out, "keymap.c"), "w", newline="\n").write("\n".join(out) + "\n")

    # ---- layout_settings.h
    h = [HEADER, "#pragma once", ""]
    for q, v in settings:
        if q in QSID_MACROS:
            h.append("#define {} {}".format(QSID_MACROS[q], v))
    open(os.path.join(args.out, "layout_settings.h"), "w", newline="\n").write("\n".join(h) + "\n")

    print("generated keymap.c ({} layers, {} tap dances, {} combos, {} key overrides, {} macros bytes, {} settings)".format(
        used, len(td), len(combos), len(kos), len(macro_blob), len(settings)))


if __name__ == "__main__":
    main()
